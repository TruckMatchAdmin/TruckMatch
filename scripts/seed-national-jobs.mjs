async function seed() {
  console.log("Démarrage de l'injection du catalogue national des offres...");
  let inserted = 0;
  let updated = 0;

  for (const job of NATIONAL_JOBS) {
    const { data: existing } = await supabase
      .from("jobs")
      .select("id")
      .eq("external_id", job.external_id)
      .maybeSingle();

    const payload = {
      title: job.title,
      company_name: job.company_name,
      contact_email: job.contact_email,
      category: job.category,
      permit_required: job.permit_required,
      contract_type: job.contract_type,
      location_city: job.location_city,
      location_department: job.location_department,
      salary_range: job.salary_range,
      schedule: job.schedule,
      benefits: job.benefits,
      description: job.description,
      requirements: job.requirements,
      status: "approved",
      is_active: true,
      source: job.source,
      external_id: job.external_id,
      apply_url: job.apply_url,
      updated_at: new Date().toISOString(),
    };

    if (existing?.id) {
      const { error: updErr } = await supabase.from("jobs").update(payload).eq("id", existing.id);
      if (!updErr) updated++;
      else console.error("Erreur update:", updErr.message);
    } else {
      const { error: insErr } = await supabase.from("jobs").insert([
        {
          ...payload,
          published_at: new Date().toISOString(),
          created_at: new Date().toISOString(),
        },
      ]);
      if (!insErr) inserted++;
      else console.error("Erreur insert:", insErr.message);
    }
  }

  const { count } = await supabase.from("jobs").select("*", { count: "exact", head: true });
  console.log(`✅ Succès : ${inserted} insérées, ${updated} mises à jour. Total offres en base : ${count}`);
}

seed();
